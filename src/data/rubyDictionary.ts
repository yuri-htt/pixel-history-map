/**
 * テキスト内の漢字に自動的にルビを振る関数
 * @param text ルビを振りたいテキスト
 * @returns ルビタグ付きのテキスト
 */
export function autoRuby(text: string): string {
  let result = text;

  // 辞書の各エントリーに対して、長い単語から順に処理（部分一致を防ぐため）
  const entries = Object.entries(rubyDictionary).sort(
    (a, b) => b[0].length - a[0].length
  );

  for (const [kanji, reading] of entries) {
    // 既にrubyタグ内にある文字列はスキップするため、
    // rubyタグの外側にある該当文字列のみを置換
    const parts = result.split(/(<ruby>.*?<\/ruby>)/g);
    result = parts
      .map((part, index) => {
        // rubyタグ部分（奇数インデックス）はそのまま、それ以外は置換
        if (part.startsWith("<ruby>")) {
          return part;
        }
        return part.replace(new RegExp(kanji, "g"), `<ruby>${kanji}<rt>${reading}</rt></ruby>`);
      })
      .join("");
  }

  return result;
}

/**
 * 既存のrubyタグ付きテキストから漢字だけを抽出
 * @param html rubyタグを含むHTML文字列
 * @returns 漢字のみのテキスト
 */
export function stripRuby(html: string): string {
  return html.replace(/<ruby>(.*?)<rt>.*?<\/rt><\/ruby>/g, "$1");
}
